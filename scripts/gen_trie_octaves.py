#!/usr/bin/env python3
"""Generate RubiksGN/TrieOctaves.lean: for each octave 2^x <= n < 2^(x+1), x < 64, the block size S and a chunk size per key,
minimizing the bound F of RubiksGN/MainTrie.lean at n = 2^x:
  F = R n^2 + (4 S (3 + 1100 (S + 2)) + 4 Sl) n + 1624 S + 8 S Sl,   the bound on trieExactW is F / (4 S n^2) * n^2.
Prints the value (x + 1) F / (4 S n^2) per octave, and its supremum over x >= k.
Usage: uv run python scripts/gen_trie_octaves.py
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from constants_exact import WEIGHTS

KS = [(t[0], t[1]) for t in WEIGHTS]
DK = sorted(set(KS))
LO, HI = 8, 64


def geom(m, s):
    return (m ** s - 1) // (m - 1)


def F(n, S, sd):
    A = S // 2
    R = sum(A // sd[k] + 1 for k in KS)
    Sl = sum((A // sd[k] + 1) * (2 * k[1] * geom(k[0], sd[k])) for k in KS)
    return R * n ** 2 + (4 * S * (3 + 1100 * (S + 2)) + 4 * Sl) * n + 1624 * S + 8 * S * Sl


def best(x):
    n = 2 ** x
    res = None
    Ss = set()
    v = 2.0
    while v < 4 * n:
        Ss.add(int(v) // 2 * 2 or 2)
        v *= 1.04
    for S in sorted(Ss):
        A = S // 2
        sd = {}
        for k in DK:
            m, w = k
            bl = None
            s = 1
            while True:
                g = 2 * w * geom(m, s)
                val = (A // s + 1) * (n ** 2 + 4 * n * g + 8 * S * g)
                if bl is None or val < bl[0]:
                    bl = (val, s)
                if m ** s > 4 * n:
                    break
                s += 1
            sd[k] = bl[1]
        f = F(n, S, sd)
        q = f / (4 * S * n ** 2)
        if res is None or q < res[0]:
            res = (q, S, sd)
    return res


def main():
    rows = {}
    out = []
    for x in range(LO, HI):
        q, S, sd = best(x)
        rows[x] = q * (x + 1)
        out.append('  (%d, %d, [%s])' % (x, S, ', '.join('((%d, %d), %d)' % (k[0], k[1], sd[k]) for k in DK)))
    src = """import Mathlib

/-!
# The parameters of the octaves `2 ^ x ≤ n < 2 ^ (x + 1)`, `x < 64`

Generated by `scripts/gen_trie_octaves.py`. Do not edit. An entry is `(x, S, [(key, chunk size)])`.
-/

namespace RubiksGN

/-- The parameters per octave. -/
def octTable : List (ℕ × ℕ × List ((ℕ × ℕ) × ℕ)) := [
%s]

end RubiksGN
""" % ',\n'.join(out)
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'RubiksGN', 'TrieOctaves.lean')
    with open(path, 'w') as f:
        f.write(src)
    print('x  (x+1)F/(4 S n^2)')
    for x in rows:
        print(x, '%.3f' % rows[x])
    print('sup over x >= k')
    for k in rows:
        print(k, '%.3f' % max(rows[x] for x in range(k, HI)))


if __name__ == '__main__':
    main()
