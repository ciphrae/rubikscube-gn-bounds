"""Write RubiksGN/UnivData.lean: a stabilizer chain of Alt(24) whose Schreier-tree edges are letters."""
import sys,random; sys.path.insert(0,'scripts')
from rot import *
SH=[(True,True),(True,False),(False,True),(False,False)]
def alpha(d): return RX if d else RXi
def beta(d): return MUL[RX if d else RXi][RZi]
LET={}
for t in range(24):
    for da,db in SH:
        for f in (False,True):
            c=(t,MUL[t][alpha(da)],MUL[t][beta(db)])
            if f: c=(c[0],c[2],c[1])
            LET[(t,da,db,f)]=c
def lact(L,k):
    c=LET[L]
    return c[(c.index(k)+1)%3] if k in c else k
def prodf(T,k):
    for L in reversed(T): k=lact(L,k)
    return k
ORDERB=[9,15,16,10,12,19,7,17,8,1,23,21,18,3,4,14,22,5,11,2,6,0]
rem=set(range(24)); levels=[]; fixed=[]
for b in ORDERB:
    # BFS from the root: letter maps parent->child; all letter points in rem
    par={b:None}; fr=[b]; depth={b:0}; order=[]
    usable=[L for L,c in LET.items() if all(p in rem for p in c)]
    while fr:
        nf=[]
        for u in fr:
            for L in usable:
                c=LET[L]
                if u in c:
                    v=lact(L,u)
                    if v not in par:
                        par[v]=(u,L); depth[v]=depth[u]+1; nf.append(v)
        fr=nf
    assert set(par)==rem
    nodes=sorted([x for x in rem if x!=b],key=lambda x:-depth[x])
    Ls=[par[x][1] for x in nodes]        # deepest edge first (head of list applied last)
    tab={}
    for x in rem:
        path=[];y=x
        while par[y] is not None:
            path.append(par[y][1]); y=par[y][0]
        # path is deepest-first; check it is a subsequence of Ls in that order
        T=[L for L in Ls if L in path]
        assert prodf(T,b)==x
        assert all(prodf(T,f)==f for f in fixed)
        tab[x]=T
    levels.append((b,Ls,tab))
    fixed.append(b); rem=rem-{b}
assert len(rem)==2
a,bb=sorted(rem)
D=sum(len(l[1]) for l in levels); print("D =",D,"max path",max(len(T) for l in levels for T in l[2].values()))
def lit(L): return f"({L[0]},{str(L[1]).lower()},{str(L[2]).lower()},{str(L[3]).lower()})"
out=["import RubiksGN.Orbit","","/-! Generated by `scripts/gen_univ.py`: a stabilizer chain of `Alt(24)` by letters. -/","","namespace RubiksGN","",
"/-- One level: base point, letters, and for each point a sublist moving the base point there. -/",
"abbrev ULevel := Fin 24 × List Letter × List (Fin 24 × List Letter)","",
"/-- The chain. -/","def uChain : List ULevel := ["]
rows=[]
for b,Ls,tab in levels:
    rows.append(f"  ({b}, [{','.join(lit(L) for L in Ls)}],\n   ["+",".join(f"({x},[{','.join(lit(L) for L in T)}])" for x,T in sorted(tab.items()))+"])")
out.append(",\n".join(rows)); out.append("]"); out+=["",f"/-- The two points left at the end of the chain. -/",f"def uLastA : Fin 24 := {a}",f"def uLastB : Fin 24 := {bb}","","end RubiksGN",""]
open('RubiksGN/UnivData.lean','w').write("\n".join(out))
