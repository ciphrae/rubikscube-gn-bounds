"""Write RubiksGN/SkelData.lean: symbol tables and stabilizer chains for corners, edges, centres."""
import sys,pickle,os; sys.path.insert(0,'scripts')
from skel import *
import chain as _c
cl,el,zl=pickle.load(open('scripts/chains.pkl','rb'))
LAY={-2:0,0:1,2:2}
AXN={'x':'.x','y':'.y','z':'.z'}
def symlit(m): return f"({AXN[m[0]]},{LAY[m[1]]},{'true' if m[2]==1 else 'false'})"
order=[(a,l,d) for a in 'xyz' for l in (-2,0,2) for d in (1,-1)]
def tb(p): return str(sum(v*32**i for i,v in enumerate(p)))
def tabs(P): return "[\n  "+",\n  ".join(tb(P[m]) for m in order)+"]"
def lev(levels):
    out=[]
    for b,T in levels:
        es=[]
        for x,(tp,w) in sorted(T.items(),key=lambda kv:(len(kv[1][1]),kv[0])):
            es.append("⟨["+",".join(symlit(m) for m in w)+"],"+tb(tp)+","+tb(_c.pinv(tp))+"⟩")
        out.append(f"  ⟨{b},[\n    "+",\n    ".join(es)+"]⟩")
    return "[\n"+",\n".join(out)+"]"
out=["import RubiksGN.Chain","","/-! Generated by `scripts/gen_skel.py`: chains for the corners, edges and face centres. -/","","namespace RubiksGN","",
"/-- Index of a symbol in the tables. -/",
"def symIdx (s : Sym) : ℕ :=\n  (match s.1 with | .x => 0 | .y => 6 | .z => 12) + 2 * s.2.1.val + (if s.2.2 then 0 else 1)","",
"/-- Symbol tables on corner stickers. -/","def tabC : List Tb := "+tabs(CP),"",
"/-- Symbol tables on edge stickers. -/","def tabE : List Tb := "+tabs(EP),"",
"/-- Symbol tables on face centres. -/","def tabZ : List Tb := "+tabs(FP),"",
"/-- The corner chain. -/","def cChain : List Level := "+lev(cl),"",
"/-- The edge chain. -/","def eChain : List Level := "+lev(el),"",
"/-- The face-centre chain. -/","def zChain : List Level := "+lev(zl),"","end RubiksGN",""]
open('RubiksGN/SkelData.lean','w').write("\n".join(out))
for name,l in (('c',cl),('e',el),('z',zl)):
    print(name,sum(max(len(v[1]) for v in T.values()) for b,T in l), sum(len(T) for b,T in l))
