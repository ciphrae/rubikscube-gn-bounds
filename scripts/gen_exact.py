"""Write RubiksGN/ExactData.lean from scripts/exact_chain.json.

The Lean file has one `ExactLevel` for each of the 42 lists, in list order; a final level of the json gives two of them.
Usage: uv run python scripts/gen_exact.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from rot import MUL, RX, RY, RZ, act

OUT = os.path.join(HERE, '..', 'RubiksGN', 'ExactData.lean')

HEADER = """import RubiksGN.PassAction

/-!
# The exact universal lists

Generated by `scripts/gen_exact.py` from `scripts/exact_chain.json` (`scripts/exact_chain.py`, verified by
`scripts/check_exact_chain.py`). Do not edit.

All points are raw coordinates of `RubiksGN/PassAction.lean`: target points and `c` on the target model, mirror points and
`D` on the mirror model. With `eT t = conjT t true * colK⁻¹` and `eM t = conjM t true * colM⁻¹`:

* `c` is the cycle of `conjT t true` and `D` the cycle of `conjM t true`, written `[a, b, c, d]` for `a ↦ b ↦ c ↦ d ↦ a`;
* a level of kind `T` (resp. `M`) has one entry for each point of `omega`, the complement of `F` (resp. `P`), and
  `images` lists `eT t (base)` (resp. `eM t (base)`) entry by entry;
* every entry of a level has `eT t` fixing `F` and `eM t` fixing `P`, and these are the points placed by the earlier levels;
* `late` means that the element of the other chain is `1`; this also holds on the final levels;
* the final levels of a chain are two consecutive lists `X`, `Y` on the five points `omega`, with `X * Y = Alt(omega)`, and
  `exactTableT`, `exactTableM` give for the images of the three points `base` the indices in `X` and `Y`.
-/

namespace RubiksGN

/-- The kind of a list: a chain level of the target or the mirror, or a list of a final factorization. -/
inductive ExactKind
  | T | M | TX | TY | MX | MY
  deriving DecidableEq, Repr

/-- A template with the two cycles it produces. -/
structure ExactEntry where
  tmpl : Tmpl
  c : List (Fin 24)
  D : List (Fin 24)
  deriving Repr

/-- One of the 42 lists, with its chain metadata. -/
structure ExactLevel where
  kind : ExactKind
  late : Bool
  base : List (Fin 24)
  F : List (Fin 24)
  P : List (Fin 24)
  omega : List (Fin 24)
  images : List (Fin 24)
  entries : List ExactEntry
  deriving Repr
"""


def b(v):
    return 'true' if v else 'false'


def letter(l):
    return f'(.{l[0]}, {b(l[1])}, {b(l[2])})'


def tmpl(t):
    return '[' + ', '.join('⟨[' + ', '.join(letter(l) for l in f) + '], ' + letter(r) + '⟩' for f, r in t) + ']'


def nums(xs):
    return '[' + ', '.join(map(str, xs)) + ']'


def entry(e):
    return '⟨' + tmpl(e['template']) + ', ' + nums(e['c']) + ', ' + nums(e['D']) + '⟩'


def level(name, kind, late, base, lv, images, entries):
    out = [f'def {name} : ExactLevel where', f'  kind := .{kind}', f'  late := {b(late)}', f'  base := {nums(base)}',
           f'  F := {nums(lv["F"])}', f'  P := {nums(lv["P"])}', f'  omega := {nums(lv["omega"])}',
           f'  images := {nums(images)}', '  entries := [']
    out += ['    ' + entry(e) + (',' if i + 1 < len(entries) else '') for i, e in enumerate(entries)]
    out.append('  ]')
    return '\n'.join(out) + '\n'


def table(name, doc, tab):
    rows = ['  (' + nums(k) + f', {i}, {j})' for k, i, j in tab]
    return f'/-- {doc} -/\ndef {name} : List (List (Fin 24) × ℕ × ℕ) := [\n' + ',\n'.join(rows) + '\n]\n'


def main():
    with open(os.path.join(HERE, 'exact_chain.json')) as fh:
        data = json.load(fh)
    parts = [HEADER]
    names = []
    tables = {}
    for lv in data['levels']:
        n = f'exactL{len(names)}'
        if lv['kind'] in ('T', 'M'):
            parts.append(level(n, lv['kind'], lv['late'], lv['base'], lv, [e['image'] for e in lv['entries']], lv['entries']))
            names.append(n)
        else:
            k = lv['kind'][0]
            parts.append(level(n, k + 'X', True, lv['base'], lv, [], lv['X']))
            names.append(n)
            n = f'exactL{len(names)}'
            parts.append(level(n, k + 'Y', True, lv['base'], lv, [], lv['Y']))
            names.append(n)
            tables[k] = lv['table']
    assert len(names) == 42
    parts.append('/-- The levels, in list order (first list leftmost in the products). -/\n'
                 'def exactLevels : List ExactLevel :=\n  [' + ', '.join(names) + ']\n')
    parts.append('/-- The universal lists. -/\ndef exactLists : List (List Tmpl) :=\n'
                 '  exactLevels.map fun l => l.entries.map ExactEntry.tmpl\n')
    parts.append(table('exactTableT', 'The target witnesses: images of `base`, index in `X`, index in `Y`.', tables['T']))
    parts.append(table('exactTableM', 'The mirror witnesses: images of `base`, index in `X`, index in `Y`.', tables['M']))

    # a validation of the syntax and of the semantics on one template
    sample = max((e for lv in data['levels'] for e in lv.get('entries', ())), key=lambda e: (len(e['template']), sum(len(f) for f, _ in e['template'])))
    nl, ne = next((i, lv['entries'].index(sample)) for i, lv in enumerate(data['levels']) if sample in lv.get('entries', ()))
    values = _evaluate(sample['template'])
    parts.append('/-- A sample template, with the values computed by `scripts/gen_exact.py`. -/\n'
                 f'def exactSample : Tmpl := {tmpl(sample["template"])}\n')
    parts.append(f"""example : exactLists.map List.length = {nums(data['sizes'])} := by
  decide +kernel
example : (exactL{nl}.entries.map ExactEntry.tmpl)[{ne}]? = some exactSample := by
  decide +kernel
example : (List.finRange 24).map (fun k => (evalT exactSample k).val) =
    {nums(values[0])} := by
  decide +kernel
example : (List.finRange 24).map (fun k => (evalTm exactSample k).val) =
    {nums(values[1])} := by
  decide +kernel
""")
    parts.append('end RubiksGN\n')
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(parts))
    print('wrote', os.path.normpath(OUT), 'levels', len(names))


def _evaluate(t):
    ax = {'x': (0, RX), 'y': (1, RY), 'z': (2, RZ)}

    def gen(a, c, d):
        i, r = ax[a]
        p = [MUL[r][k] if act(k, (-1, 2, 3))[i] == c else k for k in range(24)]
        if not d:
            q = [0] * 24
            for k, v in enumerate(p):
                q[v] = k
            p = q
        return p

    def comp(*ps):
        out = list(range(24))
        for p in reversed(ps):
            out = [p[v] for v in out]
        return out

    res = []
    for m in (1, 2):
        h = list(range(24))
        for f, r in t:
            fv = list(range(24))
            for a, s, d in f:
                fv = comp(fv, gen(a, 3 if s else -3, d))
            fi = [0] * 24
            for k, v in enumerate(fv):
                fi[v] = k
            h = comp(h, fv, gen(r[0], m if r[1] else -m, r[2]), fi)
        res.append(h)
    return res


if __name__ == '__main__':
    main()
