"""Write RubiksGN/RotData.lean: the 24 rotations and their multiplication table."""
import sys; sys.path.insert(0,'scripts')
from rot import *
names=['x','y','z']
def form(i):
    p,s=signed(i)
    return "("+", ".join(("" if s[k]>0 else "-")+names[p[k]] for k in range(3))+")"
out=["/-! Generated by `scripts/gen_rot.py`. -/","import Mathlib".strip()]
out=["import Mathlib","","/-! Generated by `scripts/gen_rot.py`: the 24 rotations of the cube. -/","","namespace RubiksGN","",
"/-- Integer vectors: stickers live on the surface of the cube `[-n,n]³`. -/","abbrev V := ℤ × ℤ × ℤ","",
"/-- The 24 proper signed permutation matrices (index `0` is the identity). -/","def actN : ℕ → V → V"]
for i in range(24):
    out.append(f"  | {i}, (x, y, z) => {form(i)}")
out.append("  | _, v => v")
out+=["","/-- Multiplication table of the rotation group: `act (mul i j) = act i ∘ act j`. -/","def mulTab : List (List ℕ) := ["]
out+=["  "+str(r)+("," if k<23 else "") for k,r in enumerate(MUL)]
out+=["]","","/-- Inverses in the rotation group. -/","def invTab : List ℕ := "+str(INV),"",
f"/-- Quarter turns about the `x`, `y`, `z` axes as rotation indices. -/",f"def rxN : ℕ := {RX}",f"def ryN : ℕ := {RY}",f"def rzN : ℕ := {RZ}","","end RubiksGN",""]
open('RubiksGN/RotData.lean','w').write("\n".join(out))
print(ID,RX,RY,RZ,form(RX),form(RY),form(RZ))
